    private int ambilJumlahPembelian() {
        Object nilai = spnJumlah.getValue();
        if (nilai instanceof Integer) {
            return Math.max(1, (Integer) nilai);
        }
        try {
            return Math.max(1, Integer.parseInt(nilai.toString().trim()));
        } catch (Exception e) {
            return 1;
        }
    }

